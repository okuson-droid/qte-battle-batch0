def load_names():
    cards = json.load(open(MASTER, encoding='utf-8'))['cards']
    return {c['name']: c for c in cards}


def main():
    check = '--check' in sys.argv
    names = load_names()

    order = ['1', '2', '3a', '3b', '4', '5']
    grouped = {c: [] for c in order}
    missing = []
    for name, (cat, note) in TRIAGE.items():
        if name not in names:
            missing.append(name)
            continue
        grouped[cat].append((name, note))

    total = 0
    for cat in order:
        cards = grouped[cat]
        total += len(cards)
        print(f'=== 区分{cat}({len(cards)}枚) ===')
        for name, note in sorted(cards):
            print(f'  {name}' + (f'  …… {note}' if note else ''))
        print()

    print(f'合計: {total}枚(rework-triage.md の見込み121枚)')

    if missing:
        print('NG: manual-cards.json に見つからないカードがある:', ', '.join(missing))

    if check:
        ok = not missing and total == 121
        if not ok:
            print('NG: 仕分け表の整合性チェックに失敗した')
            sys.exit(1)
        print('OK: 121枚すべてが manual-cards.json に実在し、区分の合計も一致する')


if __name__ == '__main__':
    main()
