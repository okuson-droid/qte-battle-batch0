package com.example.qte.manual;

/**
 * 「儀式」の種類(★Batch 38 設計書2章)。
 *
 * <h2>★これは差分の種類ではない</h2>
 * 32a 以来、盤面の演出はすべて<b>ビューの差分</b>から検出してきた。
 * ここに並ぶのは、いずれも<b>差分では語れない出来事</b>である。
 *
 * <ul>
 *   <li>開始シーケンス —— 盤面の<b>総入れ替え</b>であり、差分が語れる「1手」ではない
 *       ({@code applyView} は {@code fxStartLocking} の間そもそも差分を採っていない)</li>
 *   <li>山札のシャッフル —— <b>盤面に何も起きない</b>。枚数もゾーンも変わらず、
 *       非公開の並びだけが変わる。差分から見れば完全な無変化である</li>
 * </ul>
 *
 * <p>裁定81 が指示したのは「差分の抑制を緩める」ことではなく
 * 「<b>別の入口から語る</b>」ことであった。この列挙体がその入口の名前である。</p>
 *
 * <h2>★★名前から "Start" を外した理由(38 追補)</h2>
 * 初版は {@code ManualStartRite} という名前だった。開始シーケンスしか例が無かったからである。
 * 手動のシャッフルを足す段になって、この器が本当に表しているのは
 * <b>「差分では語れない、員数と段取りで語る出来事」</b>だと分かった。
 * ★<b>名前は最初の例ではなく性質に付ける。</b>「開始の儀式」に無理やり
 * シャッフルを入れると、次に読む人は名前のほうを信じて混乱する。
 *
 * <h2>★★差分は同一性を語り、儀式は員数を語る</h2>
 * 開始の配り直しでカードの {@code instanceId} はすべて作り直される。
 * したがって差分から見ると全カードが「消滅して出現した」ように見え、その情報には意味が無い。
 * 一方で<b>枚数</b>には意味がある —— 先攻4枚・後攻5枚は総合ルール 2-5 そのものである。
 * 儀式が運ぶのは枚数と席だけであり、どの1枚かは運ばない。
 * ★この性質のおかげで、相手席の配りも演出できる。手札は「窓」のゾーンで中身が
 * 届かない(裁定7)が、枚数は元から公開情報である。
 */
public enum ManualRiteKind {

    /** 先後判定のダイスを振った。★対戦部屋で選択権が発生する場合だけ単独で起きる */
    DICE,

    /** シャッフルして初期ドローを配った(総合ルール 2-5 の1〜2)。★ソロではダイスと同じ配信で起きる */
    DEAL,

    /** マリガン。戻す → シャッフル → 同数引き直す(総合ルール 2-5 の3) */
    MULLIGAN,

    /**
     * 山札のシャッフル(手動操作。設計書16 5-3 の11)。
     * ★開始シーケンスの外で起きる<b>唯一の儀式</b>である。
     * ★★<b>枚数は1枚も動かない。</b>それでも {@code dealt} に席を1件持つのは、
     * 「この儀式がどの席の山札に触ったか」を運ぶためである(員数は 0 / 0 になる)。
     */
    SHUFFLE,
}
