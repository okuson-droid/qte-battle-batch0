package com.example.qte.manual;

import lombok.Getter;
import lombok.RequiredArgsConstructor;

/**
 * 部屋の種類(Batch 21 設計書 1-1)。★作成時に決め、以後変更できない。
 *
 * <h2>なぜ種類を1つの列挙体に集約するのか</h2>
 * フェイズ2で分岐する項目は「公開範囲」「操作権限」「Undo の深さ」「名前の必須性」の4つある。
 * これらを個別のフラグとして部屋に持たせると、
 * 「公開範囲だけ対戦、Undo だけ全公開」という誰も望んでいない組み合わせが表現でき、
 * 検証もその組み合わせぶん必要になる。実際に人間が選ぶのは
 * 「一人で回すのか、人と戦うのか」の1つだけである。
 *
 * <h2>途中で変更できない理由(設計書 1-1)</h2>
 * 対戦 → 全公開へ切り替えると、それまで非公開だった手札・山札の中身が
 * 遡って相手に見えることになる。ログも視点別にレンダリングしている以上、
 * 過去の行の見え方まで変わる。前提が崩れる変更は、そもそも道を作らない。
 *
 * <h2>「ソロ対戦」を独立モードにしない(設計書 1-1)</h2>
 * 設計書16 11-1 の「ソロ対戦」は<b>全公開部屋に1人(または2人)で座る運用</b>である。
 * 3種類目の部屋を作らないのは、ソロ対戦が対戦部屋と違うのは「相手がいないこと」だけで、
 * 種別として区別すべき性質が1つも無いためである。
 */
@Getter
@RequiredArgsConstructor
public enum ManualRoomType {

    /** 全公開。一人回し・ソロ対戦。視点フィルタも操作権限も効かない(現行の挙動) */
    OPEN("全公開"),

    /** 対戦。公開範囲・操作権限・Undo 1段が有効になる */
    VERSUS("対戦");

    private final String displayName;

    /** 情報保護と操作権限を働かせる部屋か。★判定はこのメソッド1つを見る。 */
    public boolean isRestricted() {
        return this == VERSUS;
    }
}
