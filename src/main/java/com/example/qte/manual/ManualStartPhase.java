package com.example.qte.manual;

import lombok.Getter;
import lombok.RequiredArgsConstructor;

/**
 * ゲーム開始シーケンスのフェーズ(Batch 23 設計書 2-1)。
 *
 * <h2>★これは「判断」ではない(設計書16 5-1 との関係)</h2>
 * 手動モードはゲームの裁定を実装しない。ここで自動化するのは
 * <b>総合ルール 2-5(ゲーム開始前の処理)だけ</b>であり、2-6(ターン進行)には一切
 * 踏み込まない(23 設計書 1-3)。2-5 の手順は盤面の状態に一切依存しない決まりきった段取りで
 * あり、アプリが引き受けるのは「乱数」と「シャッフル・移動・枚数を数えること」だけである。
 * 選択の余地があるのは<b>先攻/後攻の選択</b>と<b>マリガンで戻す札</b>の2箇所で、
 * どちらも人間が押す。
 *
 * <h2>★{@code DEALING}(配る)を状態にしない(2-1)</h2>
 * シャッフルと初期ドローは1回の操作の中で同期的に終わる。中間状態を作ると、
 * そこで止まったまま復帰できない部屋が生まれる。
 * <b>状態は「人間の入力を待っている間」だけ持つ。</b>
 *
 * <h2>★置き場所は {@link ManualRoom} である(2-6)</h2>
 * {@link ManualGameState} に入れてはならない。あちらは {@code copy()} で複製されて
 * 履歴に積まれるものであり、開始フェーズが Undo で巻き戻ると
 * 「盤面は開始済みなのにフェーズだけ未開始」という状態が作れてしまう。
 * ログ({@link ManualRoom} が持つ)と同じ側に置けば「盤面の外にある情報」という
 * 位置づけが1つに揃う。
 */
@Getter
@RequiredArgsConstructor
public enum ManualStartPhase {

    /** 未開始。従来どおりの手動モードであり、盤面は自由に操作できる */
    IDLE("未開始", false),

    /** 先攻後攻の決め方(ダイス / 自分が先攻 / 自分が後攻)を選んでいる */
    ORDER_METHOD("開始方法の選択中", true),

    /** ダイスの勝者が先攻 / 後攻を選んでいる。★ソロでは経由しない(3-1) */
    ORDER_CHOICE("先攻・後攻の選択中", true),

    /** 両者がマリガンの選択中 */
    MULLIGAN("マリガンの選択中", true),

    /** 開始済み。★リセットされるまで固定である(1-4) */
    PLAYING("対戦中", false);

    private final String displayName;

    /**
     * この間は盤面の手動操作を止めるか(7章)。
     *
     * ★止めるのは<b>サーバ</b>である({@link ManualPermissions#denyDuringStart})。
     * クライアントのモーダル・オーバーレイは操作補助にすぎない(設計判断27)。
     * ★ただしリセットだけは通す(7-2)。開始シーケンスが何かの理由で詰まったときの
     * 逃げ道であり、<b>止まったまま抜けられない画面を作らない</b>ための1つ穴である。
     */
    private final boolean locking;
}
