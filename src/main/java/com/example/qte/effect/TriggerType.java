package com.example.qte.effect;

/**
 * 効果が発動するタイミングの分類。
 *
 * ON_SUMMONとON_ENTERの区別は発注者確認済みの重要裁定:
 * 「召喚」(通常召喚・特殊召喚)ではON_SUMMONとON_ENTERの両方が発動し、
 * 効果による「出す」(墓地からの展開など)ではON_ENTERのみが発動する。
 * 【召喚時】= ON_SUMMON、【知識】などの登場時能力 = ON_ENTER。
 */
public enum TriggerType {

    /** 【召喚時】。召喚(通常・特殊)でのみ発動する */
    ON_SUMMON,

    /** 登場時。召喚か効果による「出す」かを問わず、場に出れば発動する(知識など) */
    ON_ENTER,

    /** 攻撃時(攻撃宣言したとき)。例: 波濤の突撃兵 */
    ON_ATTACK,

    /** 破壊されたとき。原因(戦闘/効果)を問わない */
    ON_DESTROYED,

    /**
     * 戦闘によって破壊されたときのみ発動する。例: ボーン・コレクター。
     * EffectContextに破壊原因を持たせる代わりに、トリガーの種類で区別している
     * (EffectContextはrecordであり、引数を増やすと全呼び出し箇所に波及するため)。
     */
    ON_DESTROYED_BY_COMBAT,

    /** ダメージを受けたとき(戦闘・効果を問わない)。例: 獄門の裁定者 */
    ON_MINION_DAMAGED,

    /** ターンエンド時。例: 詠唱の疾風騎士のスペル回収、連撃の巨岩のセルフバウンス(土文明) */
    ON_TURN_END,

    /**
     * 自分のターンのはじめ(★Batch 48。風文明のハク霊・コク霊)。
     *
     * <b>発火するのはターンプレイヤーの場だけである</b>(マスター裁定183)。
     * ON_TURN_END が両者の場を回すのと非対称だが、これは意図した非対称である ——
     * 「ターンの終わり」はターンという単位そのものの終わりであり、
     * ハク霊・コク霊の「ターンのはじめ」は自分の番が回ってくることを指す。
     * 両者の場で発火させると、自ターンに出したハク霊が相手のターン開始時に即自壊し、
     * 【守護】でも【威圧】でもない2/3の壁として一度も機能しないままになる。
     *
     * 発火位置は {@code GameService.beginTurn} のアンタップ処理の後・
     * マナチャージフェイズの前である。ドローの後に置いているのは、
     * 山札切れ敗北の判定を先に済ませるためである。
     *
     * <b>反復は場のコピーに対して行う。</b> ハク霊の自壊は【破壊時】でコク霊を
     * 場に出すため、反復中に場が増える。コピーを回すことで、
     * 「この開始時に出てきたミニオンは、この開始時にはもう処理されない」が構造的に決まる
     * (=無限ループが起こりえない)。
     */
    ON_TURN_START,

    /**
     * 戦闘で相手ミニオンを撃破したとき、撃破した側に発動する(土文明のタイタン・ウォリアー)。
     * 被害者側に発動する {@link #ON_DESTROYED_BY_COMBAT} とは「向き」が逆であり(設計判断31)、
     * 戦闘解決の破壊判定がすべて終わった後、
     * 「相手が場を離れ、かつ自分が場に残っている」側にのみ発火する。
     */
    ON_COMBAT_KILL,

    /**
     * ウェポンを装備した瞬間に発動する(土文明のガイア・ハンマー)。
     * ミニオンの召喚(ON_SUMMON/ON_ENTER)とは別のタイミングであり、
     * ウェポンは MinionInstance を持たないため、専用の入口
     * {@link com.example.qte.effect.CardEffectRegistry#fireEquip} から発火する。
     * 【知識】の装備時ドローは GameService.equipWeapon が別途処理している。
     */
    ON_EQUIP,

    /**
     * 自分がカードを1枚使用し終えたとき(風文明)。
     * 発火は効果の解決が終わった後であり、使用したカード自身の効果からは発火が見えない
     * (裁定1: 使用カウンタは自身を含まない)。
     *
     * カウンタ({@code PlayerState.cardsUsedThisTurn})を読むだけでは足りない理由:
     * 突風のまとめ役は「使用するたび、自分のミニオンすべてに+1」であり、
     * カウンタの差分で計算すると、バフが配られた後に場に出たミニオンにも遡って乗ってしまう。
     * また発生源が破壊されても配り終えたバフは残るはずだが、カウンタ参照では消えてしまう。
     * 「その瞬間に場にいるミニオンへ修正を積む」形にすることで、期限の管理は
     * 既存の修正スタック(THIS_TURN)がそのまま担う。
     */
    ON_CARD_USED,

    /**
     * 自分のミニオンが攻撃を宣言したとき(Ver.0.4の魔剣レーヴァテイン)。
     *
     * 反応するのは攻撃したミニオン自身ではなく、その持ち主が装備しているウェポンである。
     * {@link #ON_ATTACK} が「攻撃した本人に起きたこと」であるのに対し、
     * こちらは「味方に起きたこと」を横から見ている(設計判断31: トリガーには向きがある)。
     * 発火は攻撃宣言ごとであり、1体が2回攻撃すれば2回発火する(発注者確認済み)。
     *
     * 発火は {@link CardEffectRegistry#fireAllyMinionEvent} が専用の入口として行う。
     * ウェポンは MinionInstance を持たないため、ミニオン単位の {@code fire()} では拾えない。
     */
    ON_ALLY_MINION_ATTACK,

    /**
     * 自分のミニオンが場に出たとき(Ver.0.4の禁忌の冥魔剣)。
     *
     * {@link #ON_ALLY_MINION_ATTACK} と同じくウェポンが反応するトリガーである。
     * 「場に出たとき」であって【召喚時】ではないため、
     * 召喚・特殊召喚に加えて蘇生や効果による「出す」でも発動する(発注者確認済み)。
     * したがって発火箇所は {@link #ON_ENTER} と完全に同じ2箇所になる
     * (GameService.summonToField と GameActions.putIntoFieldByEffect)。
     */
    ON_ALLY_MINION_ENTER,

    /**
     * <b>相手</b>がカードを引いたとき(★Batch 59。Ver1.1 の《英知の水晶》)。
     *
     * <p>反応するのは、引いたプレイヤーから見た<b>相手の場に居るミニオン</b>である。
     * 発火は {@link CardEffectRegistry#fireOpponentDrew} が専用の入口として行い、
     * 実際に呼ぶのは {@code GameActions.drawCards}(=このゲームで山札から手札へ
     * カードが動く唯一の場所)である。
     *
     * <h2>★このトリガーだけが持つ2つの性質</h2>
     *
     * <p><b>(1) 相手の手番中に発火する。</b>他のトリガーはすべて、
     * 反応するミニオンの持ち主が手番を持っているか、少なくとも盤面の出来事に紐づいていた。
     * これは「相手がターン開始時に引いた」だけで発火する ——
     * 1ターンに最低1回、必ず起きるということである。
     *
     * <p><b>(2) 誘発によるドローでは発火しない。</b>
     * 両者が《英知の水晶》を出していると、A のドローが B に引かせ、
     * その B のドローが A に引かせ……と<b>相互に終わらない</b>。
     * 誘発の結果として引いたドローは数えない、と決めることでこれを断つ
     * ({@code GameActions} の再入ガードが担う)。
     * ★本文に書かれていない制限だが、書かれたとおりに実装すると
     * <b>ゲームが停止しない</b>ため、規則として足さざるを得ない。
     * 相互に出したときの挙動は裁定を仰いでいる(Batch 60 へ)。
     */
    ON_OPPONENT_DRAW
}
