package com.example.qte.room;

/**
 * 通常モードの席(★Batch 66)。
 *
 * <p>65 までの通常モードに席という概念は無く、部屋は「先に入った人が1人目、
 * 次に入った人が2人目」という<b>到着順のリスト</b>だった。到着順は
 * <b>入り直すと変わる</b>ため、一覧に「どちらが空いているか」を出せない。
 * 手動モードは 21a から席({@code ManualSeatId})を持っており、
 * ロビーの一覧・席選択画面はどちらもそれを土台にしている。
 *
 * <p>★<b>手動モードの {@code ManualSeatId} と共有しない。</b>
 * 通常モードのパッケージ({@code com.example.qte.room})が
 * 手動モードのパッケージ({@code com.example.qte.manual})に依存すると、
 * 「盤面の入れ物」でしかない手動モードの型が、ルールを執行する通常モードの
 * 土台になる。依存の向きは今のところ<b>どちらも他方を知らない</b>のが正であり、
 * 席という2値の列挙のために向きを作るのは高い(裁定163 と同じ筋)。
 */
public enum SeatId {
    A,
    B;

    /** 反対側の席。2人対戦しか無いので反転は全単射である */
    public SeatId other() {
        return this == A ? B : A;
    }
}
