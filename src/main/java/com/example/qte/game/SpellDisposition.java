package com.example.qte.game;

/**
 * 使用され終わったスペルの行き先の置換(設計判断: 置換効果は本来の処理をスキップする)。
 *
 * 通常、スペルは解決後に必ず {@code GameActions.disposeUsedSpell}(墓地 or 【還元】でマナ)を通る。
 * 風文明の2枚はこの行き先そのものを置き換える。
 *
 * <pre>
 *   回帰の風穴   : 追加コストを払った場合、このカードを山札の一番下に置く
 *   風弾の跳弾   : 追加コストを払った場合、墓地に置く代わりに手札に戻す
 * </pre>
 *
 * 効果側が {@code PlayerState.pendingSpellDisposition} に書き込み、
 * 呼び出し元(GameService.playSpell)が読んで消費する。
 * これは pendingSacrificeCount(死者蘇生)と同じ、
 * 「効果と呼び出し元のあいだで値を1個受け渡す」既存の型であり、新しい流儀を持ち込んでいない。
 */
public enum SpellDisposition {

    /** 墓地に置く代わりに手札へ戻す(風弾の跳弾) */
    TO_HAND,

    /** 墓地に置く代わりに山札の一番下へ置く(回帰の風穴) */
    TO_DECK_BOTTOM,

    /**
     * ★Batch 59: 【還元】を働かせず、必ず墓地へ置く(《地脈の覚醒》の2枚目。裁定276)。
     *
     * 「効果はターンに1回のみ発動する」に掛かったとき、マスターは
     * <b>「使用はできるが効果は出ない。【還元】も発動しない」</b>と裁定した。
     * 【還元】はキーワードであって効果ではない、という一般論より
     * <b>「このカードは何も起こさない」を優先する</b>読みである。
     *
     * ★他の2値と違い、これは行き先を<b>別の場所へ</b>置き換えるのではなく、
     * 通常の行き先(墓地)を<b>置き換えさせない</b>ための指示である。
     * 既定値(null)との違いは【還元】を見るか見ないかだけであり、
     * 禁忌由来のときは上位の規則(消滅)が勝つ点も他の2値と同じである。
     */
    TO_TRASH,

    /**
     * ★Batch 54: 効果自身がこのカードの行き先を決めきったので、使用後の処理を行わない。
     *
     * 《スタンディングテント》の【賢魂：2】「このミニオンを場に出す」が唯一の使い手である。
     * 場に出たカードを、そのうえで墓地へ送ってはいけない ——
     * 送ると<b>場と墓地の両方に同じカードが居る</b>ことになる。
     *
     * ★他の2値と違い、これは「置き換え先」ではなく<b>「もう動かすな」</b>という指示である。
     * 効果が実際にカードを動かせなかったとき(場が満杯・《英霊・コレキ》)は、
     * この値を<b>書かない</b>こと —— 書かなければ通常どおり墓地へ行く(マスター裁定 B6-2)。
     */
    KEPT_BY_EFFECT
}
