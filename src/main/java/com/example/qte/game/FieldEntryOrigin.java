package com.example.qte.game;

/**
 * 効果によって場に出るとき、そのカードが<b>どこから来たか</b>(★Batch 68。裁定311)。
 *
 * <h2>なぜ要るのか</h2>
 *
 * 63 までの規則は「【召喚時】は<b>召喚</b>でのみ発動し、効果による『出す』では発動しない」
 * であった(設計判断19)。裁定311 でこれが広がり、
 * <b>効果によって手札から場に出た場合も【召喚時】が発動する</b>ことになった。
 *
 * <p>したがって {@code GameActions.putIntoFieldByEffect} は
 * 「どこから出したか」を知らなければならない —— <b>呼び出し側は必ず知っている</b>
 * (手札の位置を回しているのか、墓地から拾っているのか、マナから取り出しているのか)。
 *
 * <h2>★入口を分けなかった理由</h2>
 *
 * 「手札から出す専用の入口」を1本足す形も考えたが、採らなかった。
 * あの入口は既に <b>{@code null} を返す理由が2つある</b>という難所を抱えており
 * (場が満杯 / 光霊・モアニールの置換。50 の落とし穴)、3本目の分かれ道を作ると
 * 「どちらを呼ぶか」の判断が呼び手に増える。
 * 出どころは<b>値</b>であって経路ではない、というのがこの enum の立場である。
 *
 * <p>★<b>番人</b>: 「効果で手札から場に出すカードは、すべて {@link #HAND} を渡している」を
 * {@code Batch68SummonFromHandTest} が測る。渡し忘れると【召喚時】が黙って発動しなくなり、
 * <b>症状が出るのは組み合わせたときだけ</b>なので、機械に見張らせる必要がある。
 */
public enum FieldEntryOrigin {

    /**
     * 手札から。★<b>【召喚時】が発動する</b>(裁定311)。
     *
     * <p>該当するのは、効果で手札のミニオンを場に出す9枚である ——
     * 《逆境の猛火者》《天界の守護神 ゾディアック》《光の召喚士》《神の福音》
     * 《聖なる降誕の儀式》《ギガマウス・バイト》《英術・スケアロック》
     * 《スタンディングテント》《英霊・タイガラム》。
     */
    HAND,

    /**
     * 手札以外(墓地・マナ・山札・公開領域など)から。【登場時】だけが発動する。
     *
     * <p>★<b>「召喚」はここに含まれない。</b>召喚は {@code GameService.summonToField} が
     * 扱う別の経路であり、そちらは元から ON_SUMMON と ON_ENTER の両方を焚く
     * (裁定311(a): 墓地からの召喚も「召喚」であり続ける)。
     */
    OTHER
}
